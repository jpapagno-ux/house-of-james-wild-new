// Ledger chart for Raja Ampat (Natural Earth 1:10m via world-atlas), clipped
// to the voyage area. Run: node scripts/build-chart-raja.cjs
const fs = require("fs");
const topo = require("topojson-client");
const world = require("world-atlas/countries-10m.json");
const B = { w: 129.55, e: 131.45, s: -1.25, n: 0.25 };
const W = 1000, kx = W / (B.e - B.w), ky = kx / Math.cos(((B.s + B.n) / 2) * Math.PI / 180), H = Math.round((B.n - B.s) * ky);
const P = ([x, y]) => [+((x - B.w) * kx).toFixed(1), +((B.n - y) * ky).toFixed(1)];
function clip(ring) { // Sutherland–Hodgman against the bounds (padded)
  const pad = 0.05, edges = [[p => p[0] >= B.w - pad, (a, b) => inter(a, b, 0, B.w - pad)], [p => p[0] <= B.e + pad, (a, b) => inter(a, b, 0, B.e + pad)], [p => p[1] >= B.s - pad, (a, b) => inter(a, b, 1, B.s - pad)], [p => p[1] <= B.n + pad, (a, b) => inter(a, b, 1, B.n + pad)]];
  let out = ring;
  for (const [inside, cut] of edges) {
    const input = out; out = [];
    for (let i = 0; i < input.length; i++) {
      const cur = input[i], prev = input[(i + input.length - 1) % input.length];
      if (inside(cur)) { if (!inside(prev)) out.push(cut(prev, cur)); out.push(cur); } else if (inside(prev)) out.push(cut(prev, cur));
    }
    if (!out.length) break;
  }
  return out;
}
function inter(a, b, axis, v) { const t = (v - a[axis]) / (b[axis] - a[axis]); return axis === 0 ? [v, a[1] + t * (b[1] - a[1])] : [a[0] + t * (b[0] - a[0]), v]; }
const fc = topo.feature(world, world.objects.countries);
const indo = fc.features.find((f) => f.properties.name === "Indonesia");
let d = "";
const polys = indo.geometry.type === "Polygon" ? [indo.geometry.coordinates] : indo.geometry.coordinates;
for (const poly of polys) for (const ring of poly) {
  const c = clip(ring);
  if (c.length > 2) d += "M" + c.map((p) => P(p).join(",")).join("L") + "Z";
}
const lab = (lng, lat, text) => { const [x, y] = P([lng, lat]); return { x, y, text }; };
const out = { width: W, height: H, bounds: B, land: d,
  labels: [lab(130.75, -0.22, "WAIGEO"), lab(130.75, -0.85, "BATANTA"), lab(130.95, -1.05, "SALAWATI"), lab(129.85, -0.95, "Ceram Sea"), lab(131.2, 0.12, "Pacific Ocean"), lab(130.3, -0.6, "Dampier Strait")],
  lats: [0, -0.5, -1].map((v) => ({ v, y: P([B.w, v])[1] })), lngs: [130, 130.5, 131].map((v) => ({ v, x: P([v, B.n])[0] })) };
fs.writeFileSync("lib/charts/raja-ampat.ts", `// Generated by scripts/build-chart-raja.cjs from Natural Earth 1:10m (public domain).\nexport const CHART_RAJA_AMPAT = ${JSON.stringify(out)} as const;\nexport function projectRaja(lat: number, lng: number) { const B = CHART_RAJA_AMPAT.bounds; return { x: (lng - B.w) * ${kx}, y: (B.n - lat) * ${ky} }; }\n`);
console.log("ok", W, H, (d.length / 1024).toFixed(1) + "KB");
