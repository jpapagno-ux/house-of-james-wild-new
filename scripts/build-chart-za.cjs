// Ledger chart for South Africa and its neighbours (Natural Earth 1:50m via
// world-atlas), clipped to the frame. Used for the location map on every
// South African record page. Run: node scripts/build-chart-za.cjs
const fs = require("fs");
const topo = require("topojson-client");
const world = require("world-atlas/countries-50m.json");
const B = { w: 15.6, e: 33.4, s: -35.2, n: -21.9 };
const W = 1000, kx = W / (B.e - B.w), ky = kx / Math.cos(((B.s + B.n) / 2) * Math.PI / 180), H = Math.round((B.n - B.s) * ky);
const P = ([x, y]) => [+((x - B.w) * kx).toFixed(1), +((B.n - y) * ky).toFixed(1)];
const inter = (a, b, ax, v) => { const t = (v - a[ax]) / (b[ax] - a[ax]); return ax === 0 ? [v, a[1] + t * (b[1] - a[1])] : [a[0] + t * (b[0] - a[0]), v]; };
function clip(ring) {
  const pad = 0.3, E = [[p => p[0] >= B.w - pad, (a, b) => inter(a, b, 0, B.w - pad)], [p => p[0] <= B.e + pad, (a, b) => inter(a, b, 0, B.e + pad)], [p => p[1] >= B.s - pad, (a, b) => inter(a, b, 1, B.s - pad)], [p => p[1] <= B.n + pad, (a, b) => inter(a, b, 1, B.n + pad)]];
  let out = ring;
  for (const [inside, cut] of E) { const input = out; out = []; for (let i = 0; i < input.length; i++) { const c = input[i], pv = input[(i + input.length - 1) % input.length]; if (inside(c)) { if (!inside(pv)) out.push(cut(pv, c)); out.push(c); } else if (inside(pv)) out.push(cut(pv, c)); } if (!out.length) break; }
  return out;
}
const fc = topo.feature(world, world.objects.countries);
const path = (f) => { let d = ""; const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates; for (const poly of polys) for (const ring of poly) { const c = clip(ring); if (c.length > 2) d += "M" + c.map((p) => P(p).join(",")).join("L") + "Z"; } return d; };
const get = (n) => fc.features.find((f) => f.properties.name === n);
const NB = ["Namibia", "Botswana", "Zimbabwe", "Mozambique", "eSwatini", "Lesotho"];
const lab = (lat, lng, text) => { const [x, y] = P([lng, lat]); return { x, y, text }; };
const out = {
  width: W, height: H, bounds: B, kx, ky,
  focus: path(get("South Africa")),
  neighbors: NB.map((n) => ({ name: n, d: path(get(n)) })).filter((n) => n.d),
  labels: {
    country: lab(-30.6, 23.2, "SOUTH AFRICA"),
    neighbors: [lab(-24.6, 17.6, "NAMIBIA"), lab(-22.7, 23.6, "BOTSWANA"), lab(-22.4, 30.6, "ZIMBABWE"), lab(-24.2, 33.0, "MOZ.")],
    seas: [lab(-32.6, 16.9, "Atlantic Ocean"), lab(-33.6, 30.6, "Indian Ocean")],
    areas: [],
  },
  lats: [-25, -30, -35].map((v) => ({ v, y: P([B.w, v])[1] })),
  lngs: [20, 25, 30].map((v) => ({ v, x: P([v, B.n])[0] })),
};
const ts = `// Generated by scripts/build-chart-za.cjs from Natural Earth 1:50m (public domain).
export const CHART_SOUTH_AFRICA = ${JSON.stringify(out)} as const;
`;
fs.writeFileSync("lib/charts/south-africa.ts", ts);
console.log("ok", W, H, (ts.length / 1024).toFixed(1) + "KB", out.neighbors.map((n) => n.name).join(","));
