// Builds a Ledger chart (pure SVG path data) for a country from the Natural
// Earth geometry kept in Base44's countryCharts. Run: node scripts/build-chart.cjs
const fs = require("fs");
const { CHART_COSTA_RICA: c } = require("./.cc-src.cjs");
const B = { w: -86.15, e: -82.35, s: 7.95, n: 11.35 };
const midLat = ((B.s + B.n) / 2) * Math.PI / 180;
const W = 1000;
const kx = W / (B.e - B.w);
const ky = kx / Math.cos(midLat);
const H = Math.round((B.n - B.s) * ky);
const P = ([lng, lat]) => [+((lng - B.w) * kx).toFixed(1), +((B.n - lat) * ky).toFixed(1)];
const path = (geom) => {
  const polys = geom.type === "Polygon" ? [geom.coordinates] : geom.coordinates;
  return polys.map((poly) => poly.map((ring) => "M" + ring.map((pt) => P(pt).join(",")).join("L") + "Z").join("")).join("");
};
const lab = (l) => ({ x: P([l.at[1], l.at[0]])[0], y: P([l.at[1], l.at[0]])[1], text: l.text });
const out = {
  width: W, height: H, bounds: B,
  focus: path(c.focus.geometry),
  neighbors: c.neighbors.map((f) => ({ name: f.properties.name, d: path(f.geometry) })),
  labels: { country: lab(c.labels.country), neighbors: c.labels.neighbors.map(lab), seas: c.labels.seas.map(lab), areas: c.labels.areas.map(lab) },
  lats: c.graticule.lats.map((v) => ({ v, y: P([B.w, v])[1] })),
  lngs: c.graticule.lngs.filter((v) => v > B.w && v < B.e).map((v) => ({ v, x: P([v, B.n])[0] })),
};
const ts = `// Generated by scripts/build-chart.cjs from Natural Earth 1:10m (public domain).
// A Ledger chart: plain SVG paths, so the map costs no tiles, no map library
// and renders in the server HTML.
export const CHART_COSTA_RICA = ${JSON.stringify(out)} as const;

export function projectCostaRica(lat: number, lng: number) {
  const B = CHART_COSTA_RICA.bounds;
  const kx = ${kx} , ky = ${ky};
  return { x: (lng - B.w) * kx, y: (B.n - lat) * ky };
}
`;
fs.writeFileSync("lib/charts/costa-rica.ts", ts);
console.log("ok", W, H, (ts.length / 1024).toFixed(1) + "KB");
