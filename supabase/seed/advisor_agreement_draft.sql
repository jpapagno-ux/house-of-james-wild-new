DRAFT FOR ATTORNEY REVIEW. This version is a working draft prepared for James Wild & Co LLC. It is shown so the house can test the Advisor Desk; it will be replaced by the text approved by counsel before any outside advisor signs.

## Parties

This Independent Marketing Agreement (the "Agreement") is made on the date it is signed in the Advisor Desk (the "Effective Date") between James Wild & Co LLC, a Florida limited liability company doing business as James Wild & Co., with its principal office at 13300 Southwest 98th Place, Miami, Florida 33176, registered as a Florida Seller of Travel under registration no. ST45327 (the "Company"); and the advisor named in the Advisor's details on file in the Advisor Desk (the "Advisor").

## Background

A. The Company designs and sells travel, including stays, safaris, voyages and journeys, under the James Wild & Co. name and its related brands.

B. The Advisor is an independent travel professional who wishes to market and sell the Company's travel offerings to the Advisor's own clients, as an independent contractor and not as an employee.

C. The parties wish to set out the terms on which the Advisor will do so, including the Advisor's compensation, which is set out in Schedule A.

## 1. Appointment

1.1 The Company appoints the Advisor, on a non-exclusive basis, to market and sell the travel products and services the Company offers from time to time (the "Travel Products"), and the Advisor accepts the appointment on the terms of this Agreement.

1.2 Nothing in this Agreement obliges the Advisor to sell any minimum volume, or obliges the Company to refer any client to the Advisor.

## 2. Independent contractor status

2.1 The Advisor is an independent contractor. Nothing in this Agreement creates an employment, partnership, joint venture, franchise or agency relationship, except the limited authority to market the Travel Products set out here.

2.2 The Advisor decides the Advisor's own working hours, place of work, methods and means of finding and serving clients, and may market other products and services that do not conflict with Section 9.

2.3 The Advisor has no authority to bind the Company to any contract, to make any promise or representation on the Company's behalf beyond the Company's published information, or to accept any booking except through the Company's booking systems and procedures.

2.4 The Advisor is not entitled to any salary, wages, benefits, insurance or other employment-related payments from the Company. The Advisor's only compensation is that set out in Schedule A.

## 3. The Advisor's services

3.1 The Advisor will introduce clients to the Travel Products, advise them in good faith, and submit quote requests, holds and bookings through the Company's Advisor Desk or other systems the Company provides.

3.2 Every booking is subject to the Company's published booking conditions and to the supplier's terms, which the Advisor will share with the client before a booking is made.

3.3 The Company sets the price, availability, inclusions and terms of every Travel Product. The Advisor will not quote a price or term the Company has not published or approved.

## 4. Seller of travel compliance

4.1 The Advisor will act as an independent agent of the Company within the meaning of Part XI of Chapter 559, Florida Statutes (the Florida Sellers of Travel Act), and this Agreement is the written contract that Part requires.

4.2 If the Advisor is required by Florida law to register as an independent agent, the Advisor will do so before engaging in business in Florida, will renew that registration each year, and will name the Company as a seller of travel the Advisor represents. Any registration fee is the Advisor's cost.

4.3 If the Advisor lives or does business in another state with seller of travel or similar laws, the Advisor will comply with them and give the Company evidence of compliance on request.

4.4 The Advisor will not hold unissued ticket stock or travel documents and will not hold itself out as the seller of travel.

## 5. Client payments

5.1 All payments by clients for Travel Products are made to the Company, or to the supplier where the Company directs, through the payment methods the Company provides. The Advisor will not accept, hold or control any client funds.

5.2 The Advisor will not receive any fee, commission or other consideration directly from a client for a Travel Product.

5.3 The Advisor will promptly pass to the Company any payment or document that reaches the Advisor by mistake.

## 6. Compensation

6.1 The Company will pay the Advisor the compensation set out in Schedule A, which is a share of the commission the Company actually receives from the supplier on each eligible booking the Advisor sells (the "Advisor Share").

6.2 Compensation is earned only once the client has travelled and the Company has received the supplier's commission in cleared funds. It is paid in the statement cycle set out in Schedule A.

6.3 If a booking is cancelled, refunded or charged back, or a supplier reverses or withholds its commission, the Advisor Share on that booking is reduced accordingly, and any amount already paid may be deducted from later payments.

6.4 The Company may change the Advisor's tier or share for bookings made after the change, on at least thirty (30) days' written notice. No change applies to a booking made before the change takes effect.

6.5 The Company will make a statement of each booking, the commission received and the Advisor Share available to the Advisor in the Advisor Desk. The Advisor may raise any question about a statement within sixty (60) days of it being made available.

## 7. Program fee

7.1 The Advisor will pay the program fee set out in Schedule A, if any, for access to the Advisor Desk, the Company's booking systems, training and marketing materials.

7.2 The program fee is not a franchise fee and does not buy any territory or exclusive right.

## 8. Brand and marketing

8.1 The Company grants the Advisor a limited, non-exclusive, non-transferable, revocable licence to use the James Wild & Co. name, marks and content the Company makes available, only to market the Travel Products and only in line with the Company's brand guidelines.

8.2 The Advisor will describe itself as "an independent advisor with James Wild & Co." or in other words the Company approves, and will not suggest that it is an employee or officer of the Company.

8.3 The Advisor will not register any domain, social media name or business name that includes "James Wild" or a confusingly similar name, and will not alter the Company's marks.

8.4 Advertising that names the Company or its Travel Products must be truthful and must follow the Company's published information. The Company may ask the Advisor to correct or withdraw any material.

8.5 All rights in the Company's names, marks, content, rates, systems and data remain with the Company. The licence ends when this Agreement ends.

## 9. Conflicts and non-solicitation

9.1 The Advisor may sell travel products of others, but will not use the Company's confidential information, rates or systems to do so.

9.2 During this Agreement and for twelve (12) months after it ends, the Advisor will not use the Company's confidential information to solicit the Company's suppliers to deal with the Advisor directly in place of the Company, or to solicit the Company's other advisors or staff to leave the Company.

## 10. Clients, confidentiality and data

10.1 Client relationships: to be settled by counsel and the Company before this draft is used.

10.2 Each party will keep confidential the other's non-public information, including rates, commission terms, supplier contracts, client data and system access, and use it only to perform this Agreement. This obligation survives for three (3) years after this Agreement ends, and for trade secrets and personal data for as long as they remain so.

10.3 Each party will handle clients' personal data lawfully, securely and only for the booking and service of travel, and will tell the other promptly of any loss or unauthorised access.

10.4 The Advisor will keep the Advisor Desk sign-in and authenticator code private, will not share an account, and will tell the Company at once if either may have been used by someone else.

## 11. Conduct, insurance and compliance

11.1 The Advisor will act honestly and professionally, give clients accurate information, and comply with all laws that apply to the Advisor's business, including consumer protection, privacy, anti-bribery and sanctions laws.

11.2 The Advisor will maintain, at the Advisor's cost, errors and omissions insurance in the amount the Company sets, and give the Company evidence of it on request.

11.3 The Advisor will keep the Advisor's details accurate and update them in the Advisor Desk within ten (10) days of any change.

## 12. Expenses and taxes

12.1 The Advisor bears all of its own costs of doing business, including travel, equipment, marketing, registrations, licences and insurance, unless the Company agrees in writing to pay a cost.

12.2 The Advisor is responsible for all taxes on its compensation. The Company will not withhold tax unless the law requires it, and will issue the tax forms the law requires (such as a Form 1099). The Advisor will provide a completed Form W-9 or other form the Company requests before any payment is made.

## 13. Term

This Agreement starts on the Effective Date and continues for one (1) year. It then renews automatically for further one-year periods unless either party ends it under Section 14.

## 14. Termination

14.1 Either party may end this Agreement for any reason on thirty (30) days' written notice to the other.

14.2 Either party may end this Agreement at once by written notice if the other materially breaches it and, where the breach can be put right, does not put it right within ten (10) days of notice.

14.3 The Company may end this Agreement at once by written notice, or suspend the Advisor's access to the Advisor Desk, if the Advisor handles client funds in breach of Section 5, loses a registration the law requires, acts dishonestly, or harms the Company's reputation or client relationships.

14.4 When this Agreement ends: the Advisor will stop using the Company's names and marks and return or delete its confidential information; access to the Advisor Desk ends; and bookings already confirmed are handled as set out in Schedule A. Sections 5, 6.3, 8.5, 9, 10, 12, 15 and 17 survive.

## 15. Indemnity and limitation of liability

15.1 The Advisor will indemnify the Company against losses, claims and reasonable legal costs arising from the Advisor's breach of this Agreement, negligence, misrepresentation to a client, or breach of law.

15.2 The Company will indemnify the Advisor against claims by a client arising solely from the Company's own breach of its booking conditions, where the Advisor acted in line with this Agreement.

15.3 Neither party is liable to the other for indirect or consequential loss, or loss of profit. Except for Sections 5, 10 and 15.1, each party's total liability under this Agreement in any twelve-month period is limited to the Advisor Share paid or payable in that period.

15.4 The Company is not responsible for the acts or omissions of suppliers, carriers or other third parties, and the Advisor will not represent otherwise to a client.

## 16. Electronic signature and records

The parties agree that this Agreement may be signed electronically in the Company's Advisor Desk, and that an electronic signature, together with the record of the signer, the time and the version signed, has the same effect as a handwritten signature under the federal Electronic Signatures in Global and National Commerce Act and the Florida Uniform Electronic Transaction Act (section 668.50, Florida Statutes). The Company will keep a copy of the signed version in the Advisor's file, available to the Advisor in the Advisor Desk.

## 17. General

17.1 Governing law and venue. Florida law governs this Agreement. The parties submit to the courts in Miami-Dade County, Florida.

17.2 Notices. Notices must be in writing and sent by email with a copy through the Advisor Desk, to the Company at the address in this Agreement and to the Advisor at the email in the Advisor's details.

17.3 Entire agreement. This Agreement, with its Schedules and the Company's published policies it refers to, is the whole agreement between the parties on its subject and replaces any earlier understanding.

17.4 Changes. A change to this Agreement binds the parties only if made in writing and accepted by both, including by electronic acceptance in the Advisor Desk. The Company may update Schedule A only as Section 6.4 allows.

17.5 Assignment. The Advisor may not assign or subcontract this Agreement without the Company's written consent. The Company may assign it to a successor to its business.

17.6 Severability and waiver. If any part of this Agreement is found unenforceable, the rest continues in effect. A failure to enforce a right is not a waiver of it.

17.7 Counterparts. This Agreement may be signed in counterparts, each of which is an original.

## Schedule A: Compensation plan

The Advisor's tier, Advisor Share, program fee and payment terms are those shown in the Advisor's compensation plan in the Advisor Desk and acknowledged there, as changed from time to time under Section 6.4. The commissionable amount is the commission the supplier pays the Company on the booking, after offers and discounts and excluding taxes, fees, service charges and non-commissionable items.

## Schedule B: Advisor information

The Advisor's details as completed in the Advisor Desk.

## Schedule C: Documents on file

A tax form (Form W-9, or Form W-8BEN outside the United States); errors and omissions insurance; any seller of travel or independent agent registration the law requires; business registration if trading through an entity; certificates as applicable.
